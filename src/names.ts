/** 種の名前（Kind の順）。記録では、まだ照らされていない種は名前を伏せる */
export const NAMES = [
  'ウィスプ', 'コウモリ', '大ネズミ', '大トカゲ', '大グモ', 'スライム', 'ゾンビ', 'ゴースト', 'マイコニド', 'ジャイアントアント',
  'コボルト', 'サラマンダー', 'ゴブリン', 'オーク', 'リザードマン', 'ミノタウロス', 'トロール', 'バジリスク', 'ガーゴイル', 'ヴァンパイア',
  'ミミック', 'ゴーレム', 'ワーム', 'ワイバーン', 'ドラゴン', '冒険者', 'スケルトン', 'リッチ', 'ドワーフ',
];
export const JOB_NAMES = ['戦士', '魔法使い', '盗賊', '僧侶', '吟遊詩人', '狩人', '竜殺し'];
/** 名前を伏せるときの呼び方 */
export const UNKNOWN = '見知らぬ影';

/** 記録の一文の中の {k:番号} を、照らされた種なら名前に、そうでなければ伏せた呼び方に置き換える */
export function renderEvent(msg: string, discovered: ArrayLike<number>): string {
  return msg.replace(/\{k:(\d+)\}/g, (_, n) => (discovered[+n] ? NAMES[+n] : UNKNOWN));
}
